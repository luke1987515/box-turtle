#!/usr/bin/env python3
"""Generate rebuilt.docx from content.json (the 'AI read the document' model).

Strategy: re-emit word/document.xml entirely from the content model.
All other package parts (styles, theme, numbering, media, header/footer,
rels, content types) are copied verbatim from the original — they are the
'design system' of the document, like reusing a company template.
Only word/document.xml is newly generated by code.
"""
import json
import os
import sys
import zipfile
from xml.sax.saxutils import escape

SRC = 'original.docx'  # default; override via argv
OUT = 'rebuilt.docx'   # default; override via argv


def emit_p(item):
    out = ['<w:p>']
    if item['pPr']:
        out.append(item['pPr'])
    for kind, val in item['content']:
        if kind == 'run':
            out.append('<w:r>')
            if val['rPr']:
                out.append(val['rPr'])
            for pkind, pval in val['parts']:
                if pkind == 't':
                    out.append(f'<w:t xml:space="preserve">{escape(pval)}</w:t>')
                else:
                    out.append(pval)
            out.append('</w:r>')
        else:  # raw atomic component (hyperlink, ...)
            out.append(val)
    out.append('</w:p>')
    return ''.join(out)


def emit_tbl(item):
    out = ['<w:tbl>']
    if item['tblPr']:
        out.append(item['tblPr'])
    if item['tblGrid']:
        out.append(item['tblGrid'])
    for row in item['rows']:
        out.append('<w:tr>')
        if row['trPr']:
            out.append(row['trPr'])
        if row['tblPrEx']:
            out.append(row['tblPrEx'])
        for cell in row['cells']:
            out.append('<w:tc>')
            if cell['tcPr']:
                out.append(cell['tcPr'])
            for it in cell['items']:
                if isinstance(it, dict):
                    out.append(emit_item(it))
                else:
                    out.append(it[1])
            out.append('</w:tc>')
        out.append('</w:tr>')
    out.append('</w:tbl>')
    return ''.join(out)


def emit_item(item):
    if item['type'] == 'p':
        return emit_p(item)
    if item['type'] == 'tbl':
        return emit_tbl(item)
    raise ValueError(item['type'])


def main():
    src = sys.argv[1] if len(sys.argv) > 1 else 'original.docx'
    out_path = sys.argv[2] if len(sys.argv) > 2 else 'rebuilt.docx'
    model = json.load(open('content.json', encoding='utf-8'))
    zin = zipfile.ZipFile(src)
    orig_doc = zin.read('word/document.xml').decode('utf-8')
    # keep the exact opening tag (namespace declarations) of the original
    i = orig_doc.index('<w:document')
    open_tag = orig_doc[i:orig_doc.index('>', i) + 1]

    body = ['<w:body>']
    for item in model['items']:
        body.append(emit_item(item))
    if model['body_sectPr']:
        body.append(model['body_sectPr'])
    body.append('</w:body></w:document>')
    new_doc = ('<?xml version="1.0" encoding="UTF-8" standalone="yes"?>'
               + open_tag + ''.join(body))

    with zipfile.ZipFile(out_path, 'w', zipfile.ZIP_DEFLATED) as zout:
        for info in zin.infolist():
            if info.filename == 'word/document.xml':
                zout.writestr(info, new_doc.encode('utf-8'))
            else:
                zout.writestr(info, zin.read(info.filename))
    zin.close()

    print('original:', os.path.getsize(src), 'bytes')
    print('rebuilt: ', os.path.getsize(out_path), 'bytes')
    print('new document.xml:', len(new_doc), 'chars (orig', len(orig_doc), ')')


if __name__ == '__main__':
    main()
